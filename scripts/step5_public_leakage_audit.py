#!/usr/bin/env python3
"""Step 5: audit whether software FORS leakage adds information beyond the public signature.

Uses ONLY artifacts generated by Step 4 from the user's own SPHINCS+ implementation.
Uses Python 3.9+ standard library. NO C source edits, new signatures, web access,
or experiments whose data are fabricated. Records only test statistics and hashes.

Run from repository root: python3 step5_public_leakage_audit.py
"""
from pathlib import Path
import hashlib
import json
import re
import sys

ROOT = Path.cwd()
CODE = ROOT / 'sphincs-sha256-128f-code'
DATA = ROOT / 'step4_public_fors_check_20261112'
OUT = ROOT / 'step5_public_leakage_audit_20261112'
N_SIG = 3

def fail(msg):
    raise SystemExit('STEP 5 FAILED: ' + msg)

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def param(source, name):
    found = re.search(r'^\s*#define\s+' + re.escape(name) + r'\s+(\d+)\b',source,re.M)
    if not found:
        fail('Cannot find ' + name + ' in params.h')
    return int(found.group(1))

def main():
    p = CODE / 'params.h'
    if not p.is_file():
        fail('Run from the SPHINCS-FORS-CORRECTED repository root.')
    if not DATA.is_dir():
        fail('Expected Step 4 output directory: ' + str(DATA))
    if OUT.exists():
        fail('Output directory already exists; rename it rather than overwrite prior results: ' + str(OUT))

    source = p.read_text(encoding='utf-8')
    n = param(source,'SPX_N')
    trees = param(source,'SPX_FORS_TREES')
    height = param(source,'SPX_FORS_HEIGHT')
    if (n,trees,height) != (16,33,6):
        fail('Unexpected code parameters; review before using this audit')
    expected_logged = N_SIG*trees*n
    paths = [DATA/'real_sk_FORS.bin', DATA/'leakage.bin', DATA/'sk_indices.bin'] + [DATA/('signature_%d.bin' % i) for i in range(1,N_SIG+1)]
    for f in paths:
        if not f.is_file():
            fail('Missing Step 4 data: ' + str(f))

    secret = paths[0].read_bytes()
    leakage = paths[1].read_bytes()
    if len(secret) != expected_logged or len(leakage) != expected_logged:
        fail('Unexpected logged file size: original=%d, leakage=%d; expected=%d' % (len(secret),len(leakage),expected_logged))

    offset_for_fors_secret = lambda j: n + j*(height+1)*n
    reconstructed_secret = bytearray()
    reconstructed_leakage = bytearray()
    per_signature = []
    for s in range(N_SIG):
        sig = (DATA / ('signature_%d.bin' % (s+1))).read_bytes()
        min_sig_size = n + trees*(height+1)*n
        if len(sig) < min_sig_size:
            fail('Signature %d is too short for defined layout' % (s+1))
        from_public = b''.join(sig[offset_for_fors_secret(j):offset_for_fors_secret(j)+n] for j in range(trees))
        derived_leak = bytes(bin(x).count('1') for x in from_public)
        reconstructed_secret.extend(from_public)
        reconstructed_leakage.extend(derived_leak)
        start,end = s*trees*n,(s+1)*trees*n
        own_log = secret[start:end]
        own_leak = leakage[start:end]
        s_matches = sum(a==b for a,b in zip(from_public,own_log))
        l_matches = sum(a==b for a,b in zip(derived_leak,own_leak))
        per_signature.append({
            'signature_number':s+1,
            'selected_bytes':trees*n,
            'public_bytes_equal_logged_secret':s_matches,
            'publicly_computable_hw_equal_logged_leakage':l_matches,
            'leakage_min':min(own_leak),
            'leakage_max':max(own_leak)
        })
        print('Signature {}: publicly readable FORS bytes {}/{}, reconstructable HW leakage {}/{}'.format(s+1,s_matches,trees*n,l_matches,trees*n))
    matching_secret = sum(a==b for a,b in zip(reconstructed_secret,secret))
    matching_leak = sum(a==b for a,b in zip(reconstructed_leakage,leakage))
    print('TOTAL: public FORS bytes equal logged blocks: {}/{}'.format(matching_secret,expected_logged))
    print('TOTAL: HW(public FORS bytes) equals logged leakage: {}/{}'.format(matching_leak,expected_logged))
    if matching_secret != expected_logged or matching_leak != expected_logged:
        fail('Mismatch found; stop and investigate before using any scientific conclusions')

    OUT.mkdir()
    report = {
        'test_name': 'Step 5 deterministic public reconstruction of the existing software leakage',
        'provenance':'User thesis/repository; 3 signatures generated in Step 4',
        'experimental_scope': 'Only software Hamming-weight leakage of the selected FORS secret bytes',
        'parameter_values': {'SPX_N':n,'SPX_FORS_TREES':trees,'SPX_FORS_HEIGHT':height},
        'signatures':N_SIG,
        'samples':expected_logged,
        'public_FORS_matches':matching_secret,
        'public_computed_HW_matches':matching_leak,
        'per_signature':per_signature,
        'input_file_hashes_sha256':{f.name:sha(f) for f in paths},
        'params_sha256':sha(p),
        'interpretation':'For the measured data, logged HW of selected FORS blocks can be computed from public signatures. It adds no information once the signatures are known. This does not assess physical leakage or unrevealed key material.',
        'not_evidence_of':'non-public key recovery, physical side-channel security, or statistically measured attack effectiveness'
    }
    outpath = OUT/'audit.json'
    outpath.write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print('STEP 5 PASS: software leakage is fully reconstructable from the public signatures in this test.')
    print('Saved:',outpath)
    print('Scientific scope: this result does NOT establish safety against physical leakage or secret-seed recovery.')

if __name__=='__main__':
    main()
